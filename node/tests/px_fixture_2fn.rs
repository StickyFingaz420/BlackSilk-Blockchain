// ---- the generator ----

fn point(n: u64) -> Point {
    Point::from_point(RistrettoPoint::mul_base(&Scalar::from(n)))
}

/// The fixture wallet and its two coinbase outputs, rebuilt exactly as
/// tests/fingerprint_fixture.rs and tests/px_fixture.rs build them.
fn fixture_wallet() -> (WalletKeys, Vec<OwnedOutput>) {
    let mut rng = ChaCha20Rng::seed_from_u64(FIXTURE_SEED);
    let (keys, _) = WalletKeys::generate(&mut rng);
    let (_payee, _) = WalletKeys::generate(&mut rng);
    let table = SubaddressTable::new(keys.view_keys(), 1, 1);
    let me = keys.address(SubaddressIndex::new(0, 0));
    let mut owned = Vec::new();
    for (height, amount) in [(1u64, 5_000_000_000u64), (2, 7_000_000_000)] {
        let cb = build_coinbase(
            height,
            &[Payment {
                address: me,
                amount,
            }],
            &keys.hedge_secret(),
            &mut rng,
        )
        .expect("a coinbase");
        let txs = [Transaction::Coinbase(cb)];
        let report = scan_block(keys.view_keys(), &table, &txs, height, height - 1);
        assert_eq!(report.owned.len(), 1);
        owned.push(report.owned[0].clone());
    }
    let f = Fixture::get();
    for o in &owned {
        let rec = f.outputs.get(&o.global_index).expect("a fixture output");
        assert_eq!(rec.key, o.key, "output {}", o.global_index);
    }
    (keys, owned)
}

/// The input plan of coinbase output 0 with the fixture transfer's first
/// ring (as tests/px_fixture.rs `plan(owned, 0)`).
fn first_plan(owned: &[OwnedOutput]) -> InputPlan {
    let per_input = RING_SIZE as u64 - 1;
    InputPlan {
        real: (&owned[0]).into(),
        decoys: (0..per_input)
            .map(|j| {
                let i = 2 + j;
                Decoy {
                    global_index: i,
                    key: OutputKey {
                        one_time_key: point(1_000 + i),
                        commitment: point(2_000 + i),
                    },
                }
            })
            .collect(),
    }
}

/// The fixture's window: bounded, so the functions' prefixes bind it.
fn window() -> Window {
    Window {
        not_before: 0,
        not_after: Fixture::get().height + WINDOW_SPAN,
    }
}

/// Builds the fixture: the transaction (proven) and the text.
fn generate() -> (Vec<u8>, String) {
    let (keys, owned) = fixture_wallet();
    let me = keys.address(SubaddressIndex::new(0, 0));
    let rules = fixture_rules();
    let (contract, _) = px2::registration();
    let mut rng = ChaCha20Rng::seed_from_u64(PX2_SEED);
    let to = Account::from_seed(&[0x22; 32]);
    let window = window();

    // The chain state: one vault record of the golden deploy's contract,
    // claimable with `secret`, at position 0 of the PX tree.
    let secret = pxw::random_digest(&mut rng);
    let record = Record {
        owner: ZERO_DIGEST,
        contract,
        asset: ZERO_DIGEST,
        value: VAULT_VALUE,
        data: vault::record_data(&contract, &secret),
        rho: pxw::random_digest(&mut rng),
        rcm: pxw::random_digest(&mut rng),
    };
    let chain = Chain2::new(&record);
    let path = chain.tree().path(0).expect("the record's path");

    // Function 0: CLAIM of the record (input 0) to `to` (output 0).
    let recipient = to.owner(0);
    let claim_blind = pxw::random_digest(&mut rng);
    let (claim_input, claim_fw) = vault::claim_call(
        &record,
        &secret,
        &Terms::claim_only(&contract, &secret),
        &recipient,
        0,
        0,
        &claim_blind,
        &window,
    );
    // Function 1: LOCK of the bridged-in RELOCK into a new vault record
    // (output 1).
    let lock_secret = pxw::random_digest(&mut rng);
    let lock_terms = Terms::claim_only(&contract, &lock_secret);
    let lock_blind = pxw::random_digest(&mut rng);
    let (lock_input, lock_fw) =
        vault::lock_call(&contract, RELOCK, &lock_terms, 1, &lock_blind, &window);

    let mut witness = pxw::witness(
        chain.tree().root(),
        RELOCK,
        0,
        [
            pxw::contract_input(&mut rng, &record, 0, path),
            pxw::dummy_input(&mut rng),
        ],
        [
            pxw::output(&mut rng, recipient, VAULT_VALUE),
            pxw::contract_output(&mut rng, contract, RELOCK, lock_terms.data(&contract)),
        ],
    );
    witness.n_fn = 2;
    witness.functions[0] = Some(claim_fw);
    witness.functions[1] = Some(lock_fw);
    let run = |input| FunctionRun {
        program: vault::program(),
        input,
        budget: vault::BUDGET,
    };
    let start = Instant::now();
    let px = build_px(
        PxPlan {
            keys: Some(&keys),
            inputs: vec![first_plan(&owned)],
            change: Some(me),
            payouts: vec![],
            witness,
            recipients: [Some(to.address(0)), Some(to.address(1))],
            functions: vec![run(claim_input), run(lock_input)],
            fee: px_standard_fee(),
            window,
            hedge_secret: [0x5f; 32],
        },
        &rules,
        &mut rng,
    )
    .expect("the two-function PX transaction builds");
    println!("build_px (proving included): {:.1?}", start.elapsed());
    let bin = Transaction::Px(Box::new(px)).encode();
    let text = format!("{HEADER}{}", record_line(&record));
    (bin, text)
}

/// Rewrites `tests/fixtures/px_fixture_2fn.bin` and `.txt` (or, with
/// `PX_FIXTURE_OUT`, writes them into that directory). Proves one
/// two-function transaction.
#[test]
#[ignore = "proves a two-function PX transaction: run alone, with at least 9 GB free"]
fn regenerate_the_two_function_px_fixture() {
    let (bin, text) = generate();
    let parsed = Px2Fixture::parse(&bin, &text).expect("the generated fixture parses");
    let h = Fixture::get().height;
    let start = Instant::now();
    let chain = Chain2::new(&parsed.record);
    assert_eq!(
        blacksilk_tx::validate::validate_px(&parsed.px, &chain, h, &fixture_rules()),
        Ok(())
    );
    println!("validate_px: {:.1?}", start.elapsed());
    let dir = std::env::var("PX_FIXTURE_OUT")
        .unwrap_or_else(|_| concat!(env!("CARGO_MANIFEST_DIR"), "/tests/fixtures").to_string());
    std::fs::create_dir_all(&dir).expect("the output directory");
    std::fs::write(format!("{dir}/px_fixture_2fn.bin"), &bin).expect("write the .bin");
    std::fs::write(format!("{dir}/px_fixture_2fn.txt"), &text).expect("write the .txt");
    println!(
        "px_fixture_2fn.bin {} bytes sha256 {}\npx_fixture_2fn.txt {} bytes sha256 {}",
        bin.len(),
        sha256_hex(&bin),
        text.len(),
        sha256_hex(text.as_bytes())
    );
}

