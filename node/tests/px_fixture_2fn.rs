/// The committed files have the pinned SHA-256, and are the canonical
/// encodings of what they decode to: the transaction re-encodes to the
/// `.bin` byte for byte and the record line re-renders the `.txt`.
#[test]
fn the_two_function_fixture_is_pinned_and_round_trips_byte_for_byte() {
    assert_eq!(sha256_hex(px2::FIXTURE_BIN), PINNED_BIN_SHA256, ".bin");
    assert_eq!(
        sha256_hex(px2::FIXTURE_TEXT.as_bytes()),
        PINNED_TXT_SHA256,
        ".txt"
    );
    let p = Px2Fixture::get();
    let bytes = Transaction::Px(Box::new(p.px.clone())).encode();
    assert!(
        bytes == px2::FIXTURE_BIN,
        "px_fixture_2fn.bin is not the canonical encoding of the decoded transaction"
    );
    assert_eq!(
        format!("{HEADER}{}", record_line(&p.record)),
        px2::FIXTURE_TEXT
    );
}

/// The documented shape: two functions of the golden deploy's vault, CLAIM
/// then LOCK; the CLAIM spends the tree's one record; one v1 input with the
/// fixture transfer's first ring; the standard fee; RELOCK bridged in; the
/// bounded window.
#[test]
fn the_two_function_fixture_has_its_shape() {
    let p = Px2Fixture::get();
    let f = Fixture::get();
    let (contract, program) = px2::registration();
    let px = &p.px;
    assert_eq!(px.functions.len(), 2);
    assert_eq!(px.public().n_fn, 2);
    for (k, sel) in [vault::CLAIM, vault::LOCK].into_iter().enumerate() {
        let fun = &px.functions[k];
        assert_eq!(fun.contract, contract, "function {k}");
        assert_eq!(fun.program_id, program.program.id(), "function {k}");
        assert_eq!(fun.outputs, vec![sel], "function {k}");
    }
    assert_eq!(
        hex::encode(program.program.id()),
        vault::VAULT_PROGRAM_ID.trim()
    );
    assert_eq!(
        (program.budget, program.abi, program.out_words),
        (vault::BUDGET, ABI_VERSION, vault::OUT_WORDS)
    );
    assert_eq!(px.window, window());
    assert_eq!(px.window.not_after, f.height + WINDOW_SPAN);
    assert_eq!(
        (px.fee, px.bridge_in, px.bridge_out),
        (px_standard_fee(), RELOCK, 0)
    );
    assert_eq!(px.inputs.len(), 1);
    assert_eq!(px.inputs[0].ring, f.transfer.inputs[0].ring);
    // The CLAIM's record: the tree's one leaf, the anchor its root, the first
    // nullifier its contract nullifier.
    let r = &p.record;
    assert_eq!(
        (r.owner, r.contract, r.asset),
        (ZERO_DIGEST, contract, ZERO_DIGEST)
    );
    assert_eq!(r.value, VAULT_VALUE);
    let chain = Chain2::new(r);
    assert_eq!(chain.px_tree_size(), 1);
    assert_eq!(px.anchor, chain.tree().root());
    let mut perm = HostPerm::new();
    let cm = r.commit(&mut perm);
    assert_eq!(
        px.nullifiers[0],
        contract_nullifier(&mut perm, &contract, &r.rcm, &cm)
    );
    // Every ring member is a fixture output.
    for i in px.inputs[0].ring {
        assert!(f.outputs.contains_key(&i), "ring member {i}");
    }
    // Nothing in common with the golden PX transaction but its v1 input.
    let golden = &PxFixture::get().px;
    assert_eq!(golden.inputs[0].key_image, px.inputs[0].key_image);
    assert_ne!(golden.anchor, px.anchor);
}

/// Full validation (PX5 included) at the fixture's height; and PX6: inside
/// the window up to its last height, `PxWindow` one past it.
#[test]
fn the_two_function_transaction_is_valid_in_its_window_only() {
    let px = &Px2Fixture::get().px;
    let h = Fixture::get().height;
    let start = Instant::now();
    assert_eq!(px2::verdict(px, h, true), Ok(()));
    println!("validate_px (full, PX5 included): {:.1?}", start.elapsed());
    let last = px.window.not_after;
    assert_eq!(px2::verdict(px, last, false), Ok(()));
    for with_proof in [false, true] {
        assert_eq!(
            px2::verdict(px, last + 1, with_proof),
            Err(TxError::PxWindow),
            "PX5 {with_proof}"
        );
    }
    assert!(!TxError::PxWindow.is_stateless());
}

/// `ZkError`'s variant by its `Debug` text (the node tests cannot name the
/// type without a new dependency; its derived `Debug` starts with the
/// variant, as in tests/px_tamper.rs).
fn zk_variant(e: &Result<(), VerifyError>) -> String {
    match e {
        Err(VerifyError::Proof(z)) => {
            let s = format!("{z:?}");
            s.split('(').next().unwrap_or("").to_string()
        }
        other => format!("{other:?}"),
    }
}

/// The proof binds each function's position, outputs and ABI, the
/// registration and the window: `blacksilk_px::prove::verify` (with the
/// arguments `check_px_proof_decoded` passes) refuses every change, with
/// the exact variant. Prints the time of each verification.
#[test]
fn the_proof_binds_both_functions_and_the_window() {
    let px = &Px2Fixture::get().px;
    let chain = Chain2::new(&Px2Fixture::get().record);
    let rules = fixture_rules();
    let h_tx = px.binding(rules.domain());
    let proof = decode_px_proof(px).expect("the proof decodes");
    let calls = chain.calls(px);
    // The control, three times (the first includes one-time setup).
    for run in 0..3 {
        let start = Instant::now();
        assert_eq!(
            chain.verify(px, &calls, &px.window, h_tx, &proof),
            Ok(()),
            "control"
        );
        println!("verify (control, run {run}): {:.1?}", start.elapsed());
    }

    // The calls swapped: each function's prefix is bound to its position.
    let swapped = vec![calls[1].clone(), calls[0].clone()];
    let start = Instant::now();
    let r = chain.verify(px, &swapped, &px.window, h_tx, &proof);
    println!("verify (swapped): {:.1?}", start.elapsed());
    assert_eq!(zk_variant(&r), "Invalid", "swapped: {r:?}");

    // The second function's output word changed (LOCK read as CLAIM).
    let mut altered = calls.clone();
    altered[1].outputs[0] = vault::CLAIM;
    let r = chain.verify(px, &altered, &px.window, h_tx, &proof);
    assert_eq!(zk_variant(&r), "Invalid", "outputs[1][0]: {r:?}");

    // Another call ABI than the registered one, on either function.
    for k in 0..2 {
        let mut other_abi = calls.clone();
        other_abi[k].abi = ABI_VERSION + 1;
        let r = chain.verify(px, &other_abi, &px.window, h_tx, &proof);
        assert_eq!(zk_variant(&r), "Invalid", "abi + 1 on function {k}: {r:?}");
    }

    // An unregistered program: the kernel program in place of the second
    // function's, and a registry that knows only the first call.
    let mut unregistered = calls.clone();
    unregistered[1].program = kernel_program();
    assert_eq!(
        chain.verify(px, &unregistered, &px.window, h_tx, &proof),
        Err(VerifyError::Unregistered(1))
    );
    let seen = std::cell::Cell::new(0);
    let first_only = |c: &blacksilk_px::core::Digest, id: &[u8; 32]| {
        seen.set(seen.get() + 1);
        if seen.get() > 1 {
            None
        } else {
            chain.px_function(c, id).map(|r| r.budget)
        }
    };
    assert_eq!(
        blacksilk_px::prove::verify(&px.public(), &calls, &px.window, h_tx, &proof, first_only),
        Err(VerifyError::Unregistered(1))
    );

    // Another window with the same h_tx: with functions the statement holds
    // the window (unlike the transfer fixture, tests/px_tamper.rs
    // `known_non_binding`).
    for w in [
        Window::UNBOUNDED,
        Window {
            not_before: 0,
            not_after: px.window.not_after + 1,
        },
        Window {
            not_before: 1,
            not_after: px.window.not_after,
        },
    ] {
        assert_ne!(w, px.window);
        let start = Instant::now();
        let r = chain.verify(px, &calls, &w, h_tx, &proof);
        println!("verify (window {w:?}): {:.1?}", start.elapsed());
        assert_eq!(zk_variant(&r), "Invalid", "window {w:?}: {r:?}");
    }

    // The same proof as a plain transfer: the call count differs.
    assert_eq!(
        blacksilk_px::prove::verify_transfer(&px.public(), h_tx, &proof),
        Err(VerifyError::Shape)
    );
}

/// The node's own path on the registration: a transaction naming another
/// program for its second function is refused as `PxUnregistered` (PX3,
/// before the signatures and the proof); a chain without the record's tree
/// does not know the anchor (PX1).
#[test]
fn the_node_refuses_an_unregistered_function_and_an_unknown_anchor() {
    let p = Px2Fixture::get();
    let h = Fixture::get().height;
    let mut v = p.px.clone();
    v.functions[1].program_id = kernel_program().id();
    for with_proof in [false, true] {
        assert_eq!(
            px2::verdict(&v, h, with_proof),
            Err(TxError::PxUnregistered { function: 1 }),
            "PX5 {with_proof}"
        );
    }
    let mut v = p.px.clone();
    v.anchor[0] ^= 1;
    assert_eq!(px2::verdict(&v, h, false), Err(TxError::PxUnknownAnchor));
}
