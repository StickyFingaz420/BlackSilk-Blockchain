//! The two-function PX fixture (`tests/fixtures/px_fixture_2fn.bin`, `.txt`;
//! `tests/support/px_fixture_2fn.rs`): a proven PX transaction with a CLAIM
//! and a LOCK of the reference vault (`n_fn = 2`, the freeze gate B2 base
//! pair) in a bounded validity window, on a synthetic chain state (one vault
//! record in the PX tree, the golden deploy's registration).
//!
//! **Test-pinned, not consensus-pinned** (decisions, "Two-function PX
//! fixture: test-pinned, CI regenerates and compares hashes, never commits"):
//! no fingerprint or manifest entry reads it. [`PINNED_BIN_SHA256`] and
//! [`PINNED_TXT_SHA256`] pin the files' SHA-256, and the round-trip tests pin
//! that the bytes are the canonical encoding of what they decode to. The
//! files sit under `tests/` and are included only in test binaries. Changing
//! them is a reviewed change (consensus-gate.sh lists their paths).
//!
//! The generator proves one two-function transaction (about 6.4 GB peak and a
//! few minutes in release); run it alone on the machine, with at least 9 GB
//! free:
//!
//! ```text
//! cargo test --release -p blacksilk-node --test px_fixture_2fn -- --ignored --exact regenerate_the_two_function_px_fixture --test-threads=1
//! ```
//!
//! It rewrites both files from fixed seeds, or, with `PX_FIXTURE_OUT=<dir>`,
//! writes them into `<dir>` instead (the determinism checks: two local runs
//! at different thread counts, and the manual workflow
//! `.github/workflows/px-fixture.yml`, which regenerates in CI and compares
//! the hashes with the committed files; CI never commits a fixture).
//!
//! The other tests verify the checked-in proof (no proving): its shape, full
//! validation, the window rule (PX6), and the refusals of
//! `blacksilk_px::prove::verify` when a function's binding is changed: the
//! calls swapped, an output word, the call ABI, an unregistered program, and
//! another window with the same `h_tx`. For a transaction without functions
//! the window enters the statement only through `h_tx`
//! (`tests/px_tamper.rs`, `known_non_binding`); with functions every
//! function's prefix carries it, so the statement itself binds it.
//! `tests/px_tamper.rs` sweeps single-byte changes of this proof too.

